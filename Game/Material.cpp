CMaterial::CMaterial()
{
    Create();
#ifdef _DEBUG
    pszGameClassName = GetGameClassName();
#endif // _DEBUG
}
/////////////////////////////////////////////////////////////////////////////////////
CMaterial::~CMaterial()
{
    Destroy();
}
/////////////////////////////////////////////////////////////////////////////////////
BOOL CMaterial::Create()
{
    szName = "none";

    SetAlpha(1);

    SetTextureMapName("none");
    SetTextureMapStrength(0);
    SetBumpMapName("none");
    SetBumpMapStrength(0);
    //
    while (!dcvStoreEmissive.empty())
        dcvStoreEmissive.pop();

    return TRUE;
}
/////////////////////////////////////////////////////////////////////////////////////
void CMaterial::Destroy()
{
    while (!dcvStoreEmissive.empty())
        dcvStoreEmissive.pop();
}
